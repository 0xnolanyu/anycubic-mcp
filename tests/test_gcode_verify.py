"""TDD tests for gcode_verify — first-layer scatter overlap + tool-sequence checks."""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from anycubic_mcp import gcode_verify as gv


def _square(cx: float, cy: float, half: float = 5.0, step: float = 1.0) -> list[tuple[float, float]]:
    pts = []
    x = cx - half
    while x <= cx + half:
        pts.append((x, cy - half))
        pts.append((x, cy + half))
        x += step
    y = cy - half
    while y <= cy + half:
        pts.append((cx - half, y))
        pts.append((cx + half, y))
        y += step
    return pts


def _write_gcode(path: Path, layers: list[list[tuple[str, tuple[float, float]]]]) -> None:
    """layers: list of (tool, (x,y)) groups; each group becomes one LAYER block."""
    lines = ["; generated by test", "M104 S200"]
    for pts in layers:
        lines.append(";LAYER_CHANGE")
        lines.append("G1 Z0.2 F600")
        last_tool = None
        for tool, (x, y) in pts:
            if tool != last_tool:
                lines.append(tool)
                last_tool = tool
            lines.append(f"G1 X{x:.3f} Y{y:.3f} E1.0 F1200")
        lines.append("G1 X0 Y0 E-1 ; retract")
    lines.append(";End of G-code")
    path.write_text("\n".join(lines), encoding="ascii")


def test_separated_objects_pass(tmp_path: Path):
    f = tmp_path / "sep.gcode"
    pts = [("T1", p) for p in _square(60, 60)] + [("T3", p) for p in _square(200, 200)]
    _write_gcode(f, [pts])
    r = gv.verify(str(f))
    assert r["ok"] is True, r
    assert len(r["clusters"]) >= 2
    assert r["overlaps"] == []
    assert r["t_sequence"] == ["T1", "T3"]
    assert r["tool_changes"] == 1  # first tool selection is initial load, not a change


def test_overlapping_objects_fail(tmp_path: Path):
    f = tmp_path / "ovl.gcode"
    # two objects at the SAME place (the real stacked-plate incident shape)
    pts = [("T1", p) for p in _square(60, 60)] + [("T3", p) for p in _square(61, 60)]
    _write_gcode(f, [pts])
    r = gv.verify(str(f))
    assert r["ok"] is False, r
    # stacked parts show up as different tools sharing one first-layer region
    assert len(r["first_layer_tool_overlap"]) + len(r["overlaps"]) >= 1


def test_object_mode_first_layer_single_cluster_ok(tmp_path: Path):
    """by-object mode prints one object per 'round'; layer 1 holds only object 1."""
    f = tmp_path / "byobj.gcode"
    layer1 = [("T1", p) for p in _square(60, 60)]
    layer2 = [("T3", p) for p in _square(200, 200)]
    _write_gcode(f, [layer1, layer2])
    r = gv.verify(str(f))
    # first layer alone cannot prove separation; ok stays True but clusters==1 and
    # tool scatter across the whole file shows two separated groups
    assert r["ok"] is True
    assert r["tool_bboxes"]["T1"] != r["tool_bboxes"]["T3"]
    assert r["t_sequence"] == ["T1", "T3"]


def test_travel_and_retract_ignored(tmp_path: Path):
    f = tmp_path / "travel.gcode"
    lines = [";LAYER_CHANGE",
             "G1 X10 Y10 E1.0 F1200",
             "G0 X200 Y200",          # travel, no E -> ignored
             "G1 X200 Y200 F9000",    # no E -> ignored
             "G1 X205 Y205 E2.0 F1200",
             ";LAYER_CHANGE", "G1 X50 Y50 E1.0"]
    f.write_text("\n".join(lines), encoding="ascii")
    pts = gv.parse_first_layer(str(f))
    assert (10.0, 10.0, "?") in pts and (205.0, 205.0, "?") in pts
    assert len([p for p in pts if p[:2] == (200.0, 200.0)]) == 0


def test_missing_file_raises():
    try:
        gv.verify("Z:/nope/missing.gcode")
        raised = False
    except FileNotFoundError:
        raised = True
    assert raised
